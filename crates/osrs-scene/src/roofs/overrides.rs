//! Each `u64` packs `(region_id << 40) | (rx1 << 32) | (ry1 << 24) | (rx2 << 16) | (ry2 << 8) | (z1 << 4) | z2`.

/// Whether world tile `(world_x, world_y)` on `plane` lies inside a RuneLite roof override box.
pub fn is_overridden_under_roof(plane: u8, world_x: i32, world_y: i32) -> bool {
    if plane > 3 || world_x < 0 || world_y < 0 {
        return false;
    }
    let region_x = (world_x >> 6) as u32;
    let region_y = (world_y >> 6) as u32;
    if region_x > 255 || region_y > 255 {
        return false;
    }
    let region_id = ((region_x << 8) | region_y) as u64;
    let rx = (world_x & 63) as u8;
    let ry = (world_y & 63) as u8;
    let start = OVERRIDES.partition_point(|&entry| (entry >> 40) < region_id);
    for &entry in &OVERRIDES[start..] {
        if (entry >> 40) != region_id {
            break;
        }
        let rx1 = ((entry >> 32) & 0xff) as u8;
        let ry1 = ((entry >> 24) & 0xff) as u8;
        let rx2 = ((entry >> 16) & 0xff) as u8;
        let ry2 = ((entry >> 8) & 0xff) as u8;
        let z1 = ((entry >> 4) & 0x0f) as u8;
        let z2 = (entry & 0x0f) as u8;
        if rx >= rx1 && rx <= rx2 && ry >= ry1 && ry <= ry2 && plane >= z1 && plane <= z2 {
            return true;
        }
    }
    false
}

