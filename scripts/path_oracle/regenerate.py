#!/usr/bin/env python3
"""Execute pinned Eiken source; only UI/history effects of smoothing are stubbed out."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true", help="compare generated bytes without rewriting fixtures")
    args = parser.parse_args()
    manifest = json.loads((HERE / "sources.json").read_text())
    for name, digest in manifest["sha256"].items():
        if hashlib.sha256((args.source / name).read_bytes()).hexdigest() != digest:
            raise SystemExit(f"Source pin mismatch: {name}")
    java_home = Path(os.environ.get("PATH_ORACLE_JAVA_HOME", "/opt/homebrew/opt/openjdk@25/libexec/openjdk.jdk/Contents/Home"))
    java, javac = java_home / "bin/java", java_home / "bin/javac"
    version = subprocess.run([java, "-version"], capture_output=True, text=True, check=True).stderr
    if manifest["java_version_line"] != version.splitlines()[0]:
        raise SystemExit(f"JDK pin mismatch: {version}")
    with tempfile.TemporaryDirectory(prefix="rustosrs-path-") as temp:
        work = Path(temp)
        shaped = (args.source / "Client/src/main/java/com/jagex/map/tile/ShapedTile.java").read_text()
        tables = []
        for name in ("tileShapePoints", "shapedTileElementData"):
            match = re.search(r"public static final int\[\]\[\] " + name + r" = (\{.*?\});", shaped, re.S)
            tables.append(f"public static final int[][] {name} = {match[1]};")
        sources = {
            "com/jagex/map/tile/ShapedTile.java": "package com.jagex.map.tile; public class ShapedTile {" + "\n".join(tables) + "}",
            "com/rspsi/tools/PathOverlayFitter.java": (args.source / "Client/src/main/java/com/rspsi/tools/PathOverlayFitter.java").read_text(),
        }
        scene = (args.source / "Client/src/main/java/com/jagex/map/SceneGraph.java").read_text()
        start = scene.index("private void smoothPathHeights(")
        body_start = scene.index("{", start)
        depth, end = 1, body_start + 1
        while depth:
            depth += (scene[end] == "{") - (scene[end] == "}")
            end += 1
        method = scene[start:end].replace("private void", "public void", 1)
        sources["SceneGraph.java"] = (HERE / "height_stubs.java.txt").read_text() + method + "\n}\n"
        for name in ("OracleMain.java", "HeightOracle.java", "OrderOracle.java"):
            sources[name] = (HERE / name).read_text()
        paths = []
        for name, source in sources.items():
            path = work / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)
            paths.append(path)
        subprocess.run([javac, "-d", work / "out", *paths], check=True)
        def run(name, *args):
            return subprocess.check_output([java, "-cp", work / "out", name, *map(str, args)])
        fit = b"# Generated from pinned EikenB00m source by scripts/path_oracle/run.sh. Do not edit.\n"
        for x, y in ((0, 0), (3200, 3200), (261, 4097)):
            fit += f"offset {x} {y}\n".encode() + run("OracleMain", x, y)
        outputs = {
            ROOT / "crates/osrs-editor/src/terrain_path/eiken_golden.txt": fit,
            ROOT / "crates/osrs-editor/src/terrain_path/java_order/golden.txt": run("OrderOracle"),
            ROOT / "crates/osrs-edit/tests/fixtures/eiken_heights.txt": run("HeightOracle"),
        }
        for path, data in outputs.items():
            if args.check:
                if not path.exists() or path.read_bytes() != data:
                    raise SystemExit(f"Fixture mismatch: {path}")
                print(f"MATCH {path.relative_to(ROOT)} ({hashlib.sha256(data).hexdigest()})")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
                print(f"Wrote {path.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
