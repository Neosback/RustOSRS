#!/bin/sh
# Regenerates crates/osrs-editor/src/terrain_path/eiken_golden.txt: the EikenB00m map editor's own
# PathOverlayFitter run on fixed paths at three map offsets. Needs a JDK and the editor's source.
#   usage: scripts/path_oracle/run.sh "/path/to/EikenB00m map editor"
set -eu
EIKEN=${1:?usage: run.sh <EikenB00m map editor checkout>}
HERE=$(cd "$(dirname "$0")" && pwd)
OUT=$HERE/../../crates/osrs-editor/src/terrain_path/eiken_golden.txt
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/src/com/jagex/map/tile" "$WORK/src/com/rspsi/tools" "$WORK/out"
# The fitter only needs the two shape tables of ShapedTile; take them from the real source.
python3 - "$EIKEN/Client/src/main/java/com/jagex/map/tile/ShapedTile.java" "$WORK/src/com/jagex/map/tile/ShapedTile.java" <<'PY'
import re, sys
text = open(sys.argv[1]).read()
tables = []
for name in ("tileShapePoints", "shapedTileElementData"):
    m = re.search(r"public static final int\[\]\[\] " + name + r" = (\{.*?\});", text, re.S)
    tables.append(f"public static final int[][] {name} = {m.group(1)};")
open(sys.argv[2], "w").write("package com.jagex.map.tile;\npublic final class ShapedTile {\n" + "\n".join(tables) + "\n}\n")
PY
cp "$EIKEN/Client/src/main/java/com/rspsi/tools/PathOverlayFitter.java" "$WORK/src/com/rspsi/tools/"
cp "$HERE/OracleMain.java" "$WORK/src/"
javac -d "$WORK/out" "$WORK"/src/com/jagex/map/tile/ShapedTile.java "$WORK"/src/com/rspsi/tools/PathOverlayFitter.java "$WORK"/src/OracleMain.java
{
  echo "# Generated by scripts/path_oracle/run.sh from the EikenB00m map editor's PathOverlayFitter. Do not edit."
  for offset in "0 0" "3200 3200" "261 4097"; do
    echo "offset $offset"
    java -cp "$WORK/out" OracleMain $offset
  done
} > "$OUT"
echo "wrote $OUT"
