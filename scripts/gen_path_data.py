#!/usr/bin/env python3
"""Generate crates/osrs-editor/src/terrain_path/census_data.rs from a path_census report.

Usage: python3 scripts/gen_path_data.py target/census/paths.json

The output is committed: the editor must not need the cache to know how real paths are tiled.
Re-run after changing the census or the pinned cache, and record the change in
docs/verification/PATH-CENSUS.md.
"""
import json
import sys
from pathlib import Path

HIDDEN_RGB = "ff00ff"  # the magenta "hidden" overlay (id 42) is never a path
MIN_COMPONENTS = 10
MIN_SHARE = 0.20


def main() -> int:
    report = json.loads(Path(sys.argv[1]).read_text())
    root = Path(__file__).resolve().parents[1]
    out = root / "crates/osrs-editor/src/terrain_path/census_data.rs"
    lines = [
        "//! Generated by `scripts/gen_path_data.py` from `path_census` (see",
        "//! `docs/verification/PATH-CENSUS.md`). Do not edit by hand.",
        "",
        "/// Per 8-neighbour occupancy mask (bit i: N, NE, E, SE, S, SW, W, NW): the number of path tiles",
        "/// with that neighbourhood, and the most common `(shape, rotation, count)` choices.",
        "pub const PRIOR: &[(u8, u32, &[(u8, u8, u32)])] = &[",
    ]
    for row in sorted(report["edges"]["prior"], key=lambda r: r["mask"]):
        top = ", ".join(f"({s}, {r}, {n})" for (s, r), n in row["top"])
        lines.append(f"    ({row['mask']}, {row['n']}, &[{top}]),")
    lines += ["];", ""]
    paths = sorted(
        o["overlay"]
        for o in report["overlays"]
        if o["rgb"] != HIDDEN_RGB
        and o["path_like_components"] >= MIN_COMPONENTS
        and o["path_like_tile_share"] >= MIN_SHARE
    )
    lines += [
        "/// Overlays the real map uses as paths (at least 10 path-like components and 20% of their tiles in",
        "/// path-like strips). Any other overlay is treated as an area (water, floors, ...) a path must",
        "/// not paint over.",
        "pub const PATH_OVERLAYS: &[u16] = &[" + ", ".join(map(str, paths)) + "];",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({len(report['edges']['prior'])} patterns, {len(paths)} path overlays: {paths})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
