#!/usr/bin/env python3
"""Generate crates/osrs-editor/src/terrain_path/census.txt from a path_census report.

Usage: python3 scripts/gen_path_data.py target/census/paths.json

The output is committed: the editor must not need the cache to know how real paths are tiled.
Re-run after changing the census or the pinned cache, and record the change in
docs/verification/PATH-CENSUS.md.
"""
import json
import sys
from pathlib import Path

HIDDEN_RGB = "ff00ff"  # the magenta "hidden" overlay (id 42) is never a path
MIN_COMPONENTS = 10
MIN_SHARE = 0.10


def main() -> int:
    report = json.loads(Path(sys.argv[1]).read_text())
    root = Path(__file__).resolve().parents[1]
    out = root / "crates/osrs-editor/src/terrain_path/census.txt"
    paths = sorted(
        o["overlay"]
        for o in report["overlays"]
        if o["rgb"] != HIDDEN_RGB
        and o["path_like_components"] >= MIN_COMPONENTS
        and o["path_like_tile_share"] >= MIN_SHARE
    )
    lines = [
        "# Generated by scripts/gen_path_data.py from path_census (see docs/verification/PATH-CENSUS.md).",
        "# P: overlays the real map uses as paths (at least 10 path-like components and 10% of their",
        "#    tiles in path-like strips); any other overlay is an area a path must not paint over.",
        "# R: 8-neighbour occupancy mask (bit i: N, NE, E, SE, S, SW, W, NW), the number of path tiles",
        "#    with it, then the most common shape,rotation,count choices.",
        "P " + " ".join(map(str, paths)),
    ]
    for row in sorted(report["edges"]["prior"], key=lambda r: r["mask"]):
        top = " ".join(f"{s},{r},{n}" for (s, r), n in row["top"])
        lines.append(f"R {row['mask']} {row['n']} {top}")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(report['edges']['prior'])} patterns, {len(paths)} path overlays)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
